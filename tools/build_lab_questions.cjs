/* Build revision records from the four labs with custom quiz renderers. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {strict: assert} = require('node:assert');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');

function between(source, start, end) {
  const from = source.indexOf(start);
  const to = source.indexOf(end, from + start.length);
  assert.ok(from >= 0 && to > from, start);
  return source.slice(from, to);
}

const hand = read('MSS-Anatomy-Lab-4.html');
const handQuestions = vm.runInNewContext([
  between(hand, 'const D=', '\nconst IMG='),
  between(hand, 'const NOTES=', '\nconst grp=') + between(hand, 'const grp=', '\n'),
  'const shuf = items => items;',
  between(hand, 'const H=', 'const labRevision='),
  'BANK'
].join('\n'));

const thigh = {window: {}};
vm.runInNewContext(read('assets/anatomy-lab-5/data.js'), thigh);
const array = (file, end) => vm.runInNewContext(between(read(file), 'const Q=[', end) + '\nQ');
const foot = array('MSS-Anatomy-Lab-6.html', 'const DROP=');
const pathology = array('MSS-Pathology-Lab-2.html', 'const labRevision=');
const rows = [];

function add(lectureId, questions) {
  questions.forEach(([question, options, answer, explanation, image], index) => {
    assert.ok(question && explanation && options[answer]);
    // Use the original index already used by the native quiz to persist attempts.
    const offset = (index + rows.length * 2) % options.length;
    const choices = options.slice(offset).concat(options.slice(0, offset));
    rows.push({id: lectureId + '-quiz-' + (index + 1), lectureId, question, options: choices,
      answer: (answer - offset + options.length) % options.length, explanation, labImage: Boolean(image)});
  });
}

add('mss-labs-anatomy-04', handQuestions.map(q => [q.q, q.o, q.a, q.e, q.f]));
add('mss-labs-anatomy-05', thigh.window.VitanovaAnatomyLab5.quiz.map(q => [q.q, q.o, 0, q.e, q.f]));
add('mss-labs-anatomy-06', foot);
add('mss-labs-pathology-02', pathology.map(q => [q.q, q.o, 0, q.e, q.i]));

const output = '/* Generated by node tools/build_lab_questions.cjs. */\n' +
  '(window.VitanovaQuestionBank ||= []).push(...' + JSON.stringify(rows) + ');\n';
const target = path.join(root, 'study-lab-questions-data.js');
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), output);
else fs.writeFileSync(target, output);
console.log('Validated ' + rows.length + ' custom lab questions.');
